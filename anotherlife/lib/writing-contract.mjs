export function writingGuideMeta(skill, prefix = 'style:') {
  const id = String(skill?.id || '');
  const body = String(skill?.body || '');
  return {
    id,
    source: id && body ? (id.startsWith(prefix) ? 'style-library' : 'writing-skill') : 'none',
    chars: body.length,
    sha256: body ? createHash('sha256').update(body, 'utf8').digest('hex') : '',
  };
}
